<?php
/**
 * ============================================================
 * 「求人」投稿の一括自動作成(表示確認用サンプル)
 * ------------------------------------------------------------
 * 前提: wordpress-snippets.php (投稿タイプ「求人」「バス会社」、
 *       都道府県タクソノミー、求人タグ、ACFフィールド)が有効な
 *       こと。
 *
 * ご注意:
 *   名簿データにあるのは「バス会社」の会社情報(住所・電話番号
 *   など)のみで、給与や雇用形態といった実際の求人内容は含まれ
 *   ていません。そのため、実在する47社のいずれかに実際の求人
 *   内容を紐付けて自動生成することはできません(事実でない給与
 *   ・待遇情報を実在の会社の求人として公開してしまうことになる
 *   ため)。
 *
 *   このスニペットは、[todofuken_directory post_type="job"]
 *   の表示確認用に、架空の会社名によるサンプル求人を12件(投稿
 *   タイプ・タクソノミー・ACFフィールドの表示テスト用)下書きで
 *   作成します。会社名はすべて架空のもので、実在するバス会社の
 *   投稿(バス会社CPT)とは一切紐付けていません。
 *
 *   実際の求人を掲載する際は、各社から得た正式な募集内容をもと
 *   に、下記のサンプルを差し替える(または個別に新規投稿する)
 *   形でご利用ください。
 * ============================================================
 */

add_action('init', function () {
    if (get_option('bj_sample_jobs_seeded')) {
        return;
    }

    if (!post_type_exists('job') || !taxonomy_exists('todofuken')) {
        return;
    }

    // slug, 架空の会社名, 勤務地, 雇用形態, 給与, タグ配列, 都道府県
    $sample_jobs = [
        ['sample-job-sapporo', 'さっぽろ交通バス(サンプル)', '北海道札幌市', '正社員', '月給22万円〜28万円', ['未経験歓迎', '免許取得支援', '中休あり'], '北海道'],
        ['sample-job-sendai', 'みちのく観光バス(サンプル)', '宮城県仙台市', '契約社員', '月給20万円〜25万円', ['寮あり', '賞与年2回'], '宮城県'],
        ['sample-job-tokyo', '関東シティバス(サンプル)', '東京都江東区', '正社員', '月給24万円〜32万円', ['未経験歓迎', '幹部登用あり'], '東京都'],
        ['sample-job-yokohama', '湘南ライナー交通(サンプル)', '神奈川県横浜市', '正社員', '月給23万円〜29万円', ['大型二種免許不要', '残業少なめ'], '神奈川県'],
        ['sample-job-nagoya', '中部トラベルバス(サンプル)', '愛知県名古屋市', '正社員', '月給22万円〜27万円', ['免許取得支援', '賞与年2回'], '愛知県'],
        ['sample-job-matsumoto', 'アルプス高速バス(サンプル)', '長野県松本市', '契約社員', '月給21万円〜26万円', ['未経験歓迎', '中休あり'], '長野県'],
        ['sample-job-osaka', 'なにわ観光バス(サンプル)', '大阪府大阪市', '正社員', '月給23万円〜30万円', ['幹部登用あり', '寮あり'], '大阪府'],
        ['sample-job-kyoto', '京都しろやまバス(サンプル)', '京都府京都市', '正社員', '月給22万円〜28万円', ['未経験歓迎', '残業少なめ'], '京都府'],
        ['sample-job-hiroshima', '瀬戸内エクスプレス(サンプル)', '広島県広島市', '正社員', '月給21万円〜26万円', ['免許取得支援', '中休あり'], '広島県'],
        ['sample-job-takamatsu', '四国みなみ交通(サンプル)', '香川県高松市', '契約社員', '月給20万円〜24万円', ['未経験歓迎', '賞与年2回'], '香川県'],
        ['sample-job-fukuoka', '博多スカイバス(サンプル)', '福岡県福岡市', '正社員', '月給22万円〜27万円', ['幹部登用あり', '寮あり'], '福岡県'],
        ['sample-job-okinawa', 'おきなわ海風バス(サンプル)', '沖縄県那覇市', '正社員', '月給21万円〜26万円', ['未経験歓迎', '免許取得支援'], '沖縄県'],
    ];

    foreach ($sample_jobs as $j) {
        [$slug, $company_name, $workplace, $employment_type, $salary, $tags, $pref] = $j;

        if (get_page_by_path($slug, OBJECT, 'job')) {
            continue;
        }

        $post_id = wp_insert_post([
            'post_type'    => 'job',
            'post_status'  => 'draft',
            'post_title'   => '【サンプル】' . $company_name . ' 路線バス運転手',
            'post_name'    => $slug,
            'post_content' => 'これは表示確認用の架空データです。実在するバス会社の求人ではありません。実際の求人を掲載する際はこの投稿を削除するか、内容を実データに差し替えてください。',
        ], true);

        if (is_wp_error($post_id) || !$post_id) {
            continue;
        }

        update_field('workplace', $workplace, $post_id);
        update_field('employment_type', $employment_type, $post_id);
        update_field('salary', $salary, $post_id);
        // company フィールドは意図的に未設定(架空データのため実在のバス会社と紐付けない)

        wp_set_object_terms($post_id, [$pref], 'todofuken', false);
        wp_set_object_terms($post_id, $tags, 'job_tag', false);
    }

    update_option('bj_sample_jobs_seeded', 1);
}, 30);
